import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

// Audited against the main and Worker bundles. Re-audit when these versions or
// the runtime imports change; npm's dependency tree also includes unused code.
const dependencies = [
  ['@bufbuild/protobuf', '2.16.0', ['third_party/protobuf-es/SOURCE.md', 'third_party/protobuf-es/LICENSE', 'third_party/protobuf-es/LICENSE-BSD']],
  ['@jax-js/jax', '0.1.27', ['node_modules/@jax-js/jax/LICENSE', 'third_party/jax-js/SOURCE.md', 'third_party/jax-js/ThirdPartyNotices.txt']],
  ['@jax-js/optax', '0.1.2', ['node_modules/@jax-js/optax/LICENSE']],
  ['fflate', '0.8.2', ['node_modules/fflate/LICENSE']],
  ['onnx-buf', '1.20.0-1', ['third_party/onnx-buf/SOURCE.md', 'third_party/onnx-buf/LICENSE-ONNX']],
  ['onnxruntime-web', '1.30.0', ['third_party/onnxruntime/SOURCE.md', 'third_party/onnxruntime/LICENSE', 'third_party/onnxruntime/ThirdPartyNotices.txt']],
  ['onnxruntime-common', '1.30.0', ['third_party/onnxruntime/LICENSE']],
  ['react', '19.3.1', ['node_modules/react/LICENSE']],
  ['react-dom', '19.3.1', ['node_modules/react-dom/LICENSE']],
  ['scheduler', '0.28.0', ['node_modules/scheduler/LICENSE']],
  ['vite', '8.3.5', ['node_modules/vite/LICENSE.md']],
];

export async function collectLicenses(target = 'public/runtime/THIRD_PARTY_LICENSES.txt') {
  const lock = JSON.parse(await readFile('package-lock.json', 'utf8'));
  const sections = [
    'Third-party software distributed with Open Vision Builder',
    'Generated by scripts/collect-licenses.mjs from the pinned npm packages and vendored upstream notices.',
    'Covers the main bundle, the ML Worker, and the copied ONNX Runtime WASM assets.',
    'These are dependency notices; they do not set the license of Open Vision Builder or its model weights.',
    'See third_party/README.md in the source repository for the audited scope and update procedure.',
  ];
  for (const [name, version, files] of dependencies) {
    const path = `node_modules/${name}`;
    const installed = JSON.parse(await readFile(join(path, 'package.json'), 'utf8'));
    const pinned = lock.packages[path];
    if (installed.version !== version || pinned?.version !== version || !pinned.integrity) {
      throw new Error(`Re-audit the runtime notices for ${name}: expected ${version}, installed ${installed.version}, lockfile ${pinned?.version}.`);
    }
    sections.push(
      `\n${'='.repeat(78)}\n${name}@${version}\n${'='.repeat(78)}`,
      `Declared npm license: ${installed.license}`,
      `Package: ${pinned.resolved}\nIntegrity: ${pinned.integrity}`,
    );
    for (const file of files) {
      let text = await readFile(file, 'utf8');
      // Only Vite's generated modulepreload helper reaches the app. The rest of
      // LICENSE.md describes dependencies of the build tool, not this bundle.
      if (name === 'vite') {
        const boundary = text.indexOf('\n# Licenses of bundled dependencies');
        if (boundary < 0) throw new Error('Re-audit the Vite runtime helper license format.');
        text = text.slice(0, boundary);
      }
      if (!text.trim()) throw new Error(`Empty runtime notice: ${file}`);
      sections.push(`\n--- ${file} ---\nSHA-256 (included text): ${createHash('sha256').update(text).digest('hex')}\n\n${text.trimEnd()}`);
    }
  }
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, `${sections.join('\n\n')}\n`);
  console.log(`Collected runtime notices for ${dependencies.length} packages in ${target}.`);
}
